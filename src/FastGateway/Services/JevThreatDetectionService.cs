/// <summary>
///     使用 Jev 对尚未判断过的 HTTP 请求记录做批量恶意行为识别。
///     jev_threat_state.last_request_id 为每 IP 的持久化水位线，保证旧记录不会重复消耗模型额度。
/// </summary>
public sealed class JevThreatDetectionService(
    JevClient client,
    ConfigurationService configService,
    ILogger<JevThreatDetectionService> logger)
{
    public const string QuestionMaliciousTraffic = "malicious_http_traffic";
    public const string QuestionAutomatedTooling = "automated_attack_tooling";

    private static readonly IReadOnlyDictionary<string, string> Questions = new Dictionary<string, string>
    {
        [QuestionMaliciousTraffic] =
            "The HTTP request history from this source contains malicious reconnaissance, exploitation attempts, or automated attack behavior rather than normal browsing or ordinary search-engine crawling. Use the host, method, path and status pairings in request_targets when deciding.",
        [QuestionAutomatedTooling] =
            "The HTTP traffic from this source was generated by attack tooling such as a vulnerability scanner, directory brute-forcer, webshell scanner, or exploit framework."
    };

    private static readonly HashSet<string> StaticExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".js", ".mjs", ".cjs", ".css", ".map", ".woff", ".woff2", ".ttf", ".otf", ".eot",
        ".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".ico", ".avif", ".bmp",
        ".mp4", ".webm", ".mov", ".avi", ".mkv", ".mp3", ".wav", ".ogg", ".flac",
        ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx", ".txt", ".md", ".csv"
    };

    private readonly SemaphoreSlim _queueLock = new(1, 1);

    public static string BuildBlacklistName(DateTimeOffset startedAt, JevThreatTrigger trigger)
    {
        var suffix = trigger == JevThreatTrigger.Manual ? "人工" : "自动";
        return $"jev-{startedAt:yyyyMMdd-HHmmss}-{suffix}";
    }

    /// <summary>普通页面、静态资源和常见文档不进入 Jev 批次，避免无意义地消耗模型额度。</summary>
    public static bool ShouldIgnoreForJev(string? rawPath)
    {
        if (string.IsNullOrWhiteSpace(rawPath)) return true;
        var path = rawPath;
        for (var i = 0; i < 2; i++)
        {
            try
            {
                var decoded = Uri.UnescapeDataString(path);
                if (decoded == path) break;
                path = decoded;
            }
            catch (UriFormatException)
            {
                break;
            }
        }

        path = path.Replace('\\', '/').ToLowerInvariant();
        if (path is "/" or "" or "/favicon.ico" or "/robots.txt" or "/sitemap.xml" or
            "/manifest.json" or "/site.webmanifest" or "/vite.svg")
            return true;
        if (path.StartsWith("/assets/", StringComparison.Ordinal) ||
            path.StartsWith("/static/", StringComparison.Ordinal) ||
            path.StartsWith("/public/", StringComparison.Ordinal))
            return true;

        var lastDot = path.LastIndexOf('.');
        var lastSlash = path.LastIndexOf('/');
        return lastDot > lastSlash && StaticExtensions.Contains(path[lastDot..]);
    }

    public JevThreatRunStatusDto StartManual()
    {
        var settings = RiskModelProviderStore.Current;
        if (!settings.IsUsable)
            throw new ValidationException("请先启用 AI 风控模型并配置 API Key");
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable)
            throw new InvalidOperationException(StatisticsDb.UnavailableReason ?? "统计数据库不可用");
        if (!_queueLock.Wait(0))
            throw new ValidationException("Jev 恶意请求判断任务正在提交，请稍后重试");

        try
        {
            using var connection = StatisticsDb.OpenWriteConnection();
            var active = ExecuteScalarInt(connection,
                "SELECT COUNT(1) FROM jev_threat_batch WHERE status IN ('queued', 'running');");
            if (active > 0)
                throw new ValidationException("已有 Jev 恶意请求判断任务排队或正在运行");

            return InsertQueuedBatch(connection, JevThreatTrigger.Manual, settings, DateTimeOffset.Now);
        }
        finally
        {
            _queueLock.Release();
        }
    }

    public JevThreatRunStatusDto? QueueAutomatic()
    {
        var settings = RiskModelProviderStore.Current;
        if (settings is not { HttpThreatEnabled: true, IsUsable: true }) return null;
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable) return null;
        if (!_queueLock.Wait(0)) return null;

        try
        {
            using var connection = StatisticsDb.OpenWriteConnection();
            var latest = Query(connection,
                    """
                    SELECT id, trigger_type, started_at, finished_at, threshold, total_candidates,
                           evaluated_ips, blocked_ips, failed_ips, blacklist_name, status, error
                    FROM jev_threat_batch
                    WHERE trigger_type = 'auto'
                    ORDER BY started_at DESC
                    LIMIT 1
                    """,
                    MapStatus)
                .FirstOrDefault();
            var interval = TimeSpan.FromHours(Math.Clamp(settings.HttpThreatIntervalHours, 1, 168));
            if (latest != null && latest.StartedAt > DateTimeOffset.Now - interval) return null;

            return InsertQueuedBatch(connection, JevThreatTrigger.Auto, settings, DateTimeOffset.Now);
        }
        finally
        {
            _queueLock.Release();
        }
    }

    public JevThreatRunStatusDto? ClaimNextQueuedBatch()
    {
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable) return null;

        using var connection = StatisticsDb.OpenWriteConnection();
        using var transaction = connection.BeginTransaction();
        var queued = Query(connection,
                """
                SELECT id, trigger_type, started_at, finished_at, threshold, total_candidates,
                       evaluated_ips, blocked_ips, failed_ips, blacklist_name, status, error
                FROM jev_threat_batch
                WHERE status = 'queued'
                ORDER BY started_at, id
                LIMIT 1
                """,
                MapStatus,
                transaction)
            .FirstOrDefault();
        if (queued == null)
        {
            transaction.Commit();
            return null;
        }

        var claimed = Execute(connection,
            "UPDATE jev_threat_batch SET status = 'running' WHERE id = @id AND status = 'queued'",
            transaction,
            new P("@id", queued.BatchId));
        if (claimed == 0)
        {
            transaction.Rollback();
            return null;
        }

        transaction.Commit();
        queued.Status = "running";
        return queued;
    }

    public async Task<JevThreatRunStatusDto> RunClaimedBatchAsync(
        JevThreatRunStatusDto queued, CancellationToken cancellationToken)
    {
        var trigger = string.Equals(queued.TriggerType, "auto", StringComparison.OrdinalIgnoreCase)
            ? JevThreatTrigger.Auto
            : JevThreatTrigger.Manual;
        try
        {
            return await RunLockedAsync(trigger, queued.StartedAt, queued.BatchId, cancellationToken);
        }
        catch (Exception ex)
        {
            MarkBatchFailed(queued.BatchId, $"后台任务失败：{ex.Message}");
            throw;
        }
    }

    public void FailInterruptedRunningJobs()
    {
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable) return;
        using var connection = StatisticsDb.OpenWriteConnection();
        Execute(connection,
            """
            UPDATE jev_threat_batch
            SET status = 'failed', finished_at = @finished, error = @error
            WHERE status = 'running'
            """,
            parameters:
            [
                new P("@finished", DateTimeOffset.UtcNow.ToUnixTimeSeconds()),
                new P("@error", "网关进程在任务完成前退出，任务已标记失败；尚未处理的排队任务会继续")
            ]);
    }

    public JevThreatRunStatusDto? GetLatestStatus(string? triggerType = null)
    {
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable) return null;

        using var connection = StatisticsDb.OpenReadConnection();
        var filter = string.IsNullOrWhiteSpace(triggerType) ? string.Empty : "WHERE trigger_type = @trigger";
        var parameters = string.IsNullOrWhiteSpace(triggerType) ? [] : new[] { new P("@trigger", triggerType) };
        return Query(connection,
                $"""
                 SELECT id, trigger_type, started_at, finished_at, threshold, total_candidates,
                        evaluated_ips, blocked_ips, failed_ips, blacklist_name, status, error
                 FROM jev_threat_batch
                 {filter}
                 ORDER BY started_at DESC
                 LIMIT 1
                 """,
                MapStatus,
                parameters: parameters)
            .FirstOrDefault();
    }

    private async Task<JevThreatRunStatusDto> RunLockedAsync(
        JevThreatTrigger trigger,
        DateTimeOffset startedAt,
        string batchId,
        CancellationToken cancellationToken)
    {
        var settings = RiskModelProviderStore.Current;
        if (!settings.IsUsable)
            throw new ValidationException("AI 风控模型未启用或 API Key 未配置");

        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable)
            throw new InvalidOperationException(StatisticsDb.UnavailableReason ?? "统计数据库不可用");

        using var connection = StatisticsDb.OpenWriteConnection();

        try
        {
            var candidates = LoadCandidates(connection, settings.HttpThreatLookbackHours);
            var selected = candidates.Take(settings.HttpThreatMaxIpsPerRun).ToList();
            var evaluated = 0;
            var failed = 0;
            var highRisk = new List<(string Ip, double Risk, string Model, long LastRequestId)>();
            var successful = new List<(ThreatCandidate Candidate, double Risk, bool Blocked)>();

            foreach (var candidate in selected)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var request = BuildRequest(settings.Model, candidate, settings.HttpThreatLookbackHours);
                var result = await client.EvaluateHttpThreatAsync(settings, request, cancellationToken);
                var now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
                var answers = result.Response?.Answers;
                var malicious = Probability(answers, QuestionMaliciousTraffic);
                var automated = Probability(answers, QuestionAutomatedTooling);

                if (!result.Success || (malicious == null && automated == null))
                {
                    failed++;
                    InsertEvaluation(connection, batchId, candidate, now, null, automated, false,
                        result.Message ?? "响应缺少恶意请求判断答案", result);
                    logger.LogWarning("Jev 恶意请求判断失败，IP {Ip}: {Error}", candidate.Ip,
                        result.Message ?? "响应缺少答案");
                    continue;
                }

                var risk = Math.Max(malicious ?? 0, (automated ?? 0) * 0.85);
                var isHighRisk = risk >= settings.HttpThreatThreshold;
                InsertEvaluation(connection, batchId, candidate, now, risk, automated, isHighRisk, null, result);
                successful.Add((candidate, risk, isHighRisk));
                evaluated++;

                if (isHighRisk) highRisk.Add((candidate.Ip, risk, result.Response?.Model ?? settings.Model,
                    candidate.LastRequestId));
            }

            var existingBlacklistIps = configService.GetBlacklistAndWhitelists()
                .Where(x => x.IsBlacklist)
                .SelectMany(x => x.Ips ?? [])
                .ToHashSet(StringComparer.OrdinalIgnoreCase);
            var blockCandidates = highRisk
                .Where(x => !existingBlacklistIps.Contains(x.Ip))
                .Where(x => !BlacklistAndWhitelistService.IsWhitelisted(x.Ip))
                .GroupBy(x => x.Ip, StringComparer.OrdinalIgnoreCase)
                .Select(x => x.OrderByDescending(y => y.Risk).First())
                .ToList();

            string? blacklistName = null;
            if (blockCandidates.Count > 0)
            {
                blacklistName = BuildBlacklistName(startedAt, trigger);
                configService.AddBlacklistAndWhitelist(new Core.Entities.BlacklistAndWhitelist
                {
                    Name = blacklistName,
                    Description = $"Jev 恶意请求判断批次 {batchId}，阈值 {settings.HttpThreatThreshold:P0}",
                    Enable = true,
                    IsBlacklist = true,
                    Ips = blockCandidates.Select(x => x.Ip).ToList()
                });
                BlacklistAndWhitelistService.RefreshCache(configService);
            }

            foreach (var item in successful)
                UpdateWatermark(connection, item.Candidate, DateTimeOffset.UtcNow.ToUnixTimeSeconds(),
                    item.Risk, batchId, item.Blocked);

            Execute(connection,
                """
                UPDATE jev_threat_batch
                SET finished_at = @finished, total_candidates = @total, evaluated_ips = @evaluated,
                    blocked_ips = @blocked, failed_ips = @failed, blacklist_name = @name, status = 'completed'
                WHERE id = @id
                """,
                parameters:
                [
                    new P("@finished", DateTimeOffset.UtcNow.ToUnixTimeSeconds()),
                    new P("@total", candidates.Count),
                    new P("@evaluated", evaluated),
                    new P("@blocked", blockCandidates.Count),
                    new P("@failed", failed),
                    new P("@name", blacklistName),
                    new P("@id", batchId)
                ]);
        }
        catch (Exception ex)
        {
            Execute(connection,
                "UPDATE jev_threat_batch SET finished_at = @finished, status = 'failed', error = @error WHERE id = @id",
                parameters:
                [
                    new P("@finished", DateTimeOffset.UtcNow.ToUnixTimeSeconds()),
                    new P("@error", ex.Message),
                    new P("@id", batchId)
                ]);
            throw;
        }

        return GetStatus(batchId) ?? new JevThreatRunStatusDto
        {
            BatchId = batchId,
            TriggerType = trigger == JevThreatTrigger.Manual ? "manual" : "auto",
            StartedAt = startedAt,
            Threshold = settings.HttpThreatThreshold,
            Status = "completed"
        };
    }

    private static JevThreatRunStatusDto InsertQueuedBatch(
        SqliteConnection connection,
        JevThreatTrigger trigger,
        RiskModelProviderSettings settings,
        DateTimeOffset startedAt)
    {
        var batchId = Guid.NewGuid().ToString("N");
        var triggerType = trigger == JevThreatTrigger.Manual ? "manual" : "auto";
        Execute(connection,
            """
            INSERT INTO jev_threat_batch
                (id, trigger_type, started_at, threshold, status)
            VALUES (@id, @trigger, @started, @threshold, 'queued')
            """,
            parameters:
            [
                new P("@id", batchId),
                new P("@trigger", triggerType),
                new P("@started", startedAt.ToUnixTimeSeconds()),
                new P("@threshold", settings.HttpThreatThreshold)
            ]);

        return new JevThreatRunStatusDto
        {
            BatchId = batchId,
            TriggerType = triggerType,
            StartedAt = startedAt,
            Threshold = settings.HttpThreatThreshold,
            Status = "queued"
        };
    }

    private static JevThreatRunStatusDto? GetStatus(string batchId)
    {
        StatisticsDb.Initialize();
        if (!StatisticsDb.IsAvailable) return null;
        using var connection = StatisticsDb.OpenReadConnection();
        return Query(connection,
                """
                SELECT id, trigger_type, started_at, finished_at, threshold, total_candidates,
                       evaluated_ips, blocked_ips, failed_ips, blacklist_name, status, error
                FROM jev_threat_batch
                WHERE id = @id
                LIMIT 1
                """,
                MapStatus,
                parameters: [new P("@id", batchId)])
            .FirstOrDefault();
    }

    private void MarkBatchFailed(string batchId, string error)
    {
        try
        {
            using var connection = StatisticsDb.OpenWriteConnection();
            Execute(connection,
                """
                UPDATE jev_threat_batch
                SET status = 'failed', finished_at = @finished, error = @error
                WHERE id = @id AND status <> 'completed'
                """,
                parameters:
                [
                    new P("@finished", DateTimeOffset.UtcNow.ToUnixTimeSeconds()),
                    new P("@error", error),
                    new P("@id", batchId)
                ]);
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "更新 Jev 后台任务失败状态时出错，批次 {BatchId}", batchId);
        }
    }

    private List<ThreatCandidate> LoadCandidates(SqliteConnection connection, int lookbackHours)
    {
        var startTs = DateTimeOffset.UtcNow.AddHours(-Math.Clamp(lookbackHours, 1, 168)).ToUnixTimeSeconds();
        var rows = Query(connection,
            """
            SELECT l.id, l.ts, l.ip, l.host, l.path, l.method, l.status, l.blocked
            FROM request_log l
            LEFT JOIN jev_threat_state s ON s.ip = l.ip
            WHERE l.id > COALESCE(s.last_request_id, 0) AND l.ts >= @startTs
            ORDER BY l.id
            """,
            r => new ThreatRequestRow(
                r.GetLong(0), r.GetLong(1), r.GetStringOrEmpty(2), r.GetStringOrEmpty(3),
                r.GetStringOrEmpty(4), r.GetStringOrEmpty(5), r.GetInt(6), r.GetInt(7)),
            parameters: [new P("@startTs", startTs)]);

        var byIp = new Dictionary<string, ThreatCandidate>(StringComparer.OrdinalIgnoreCase);
        foreach (var row in rows)
        {
            if (!AdaptiveThreatDetector.ShouldTrackIp(row.Ip)) continue;
            if (ShouldIgnoreForJev(row.Path)) continue;
            if (!byIp.TryGetValue(row.Ip, out var candidate))
            {
                candidate = new ThreatCandidate(row.Ip);
                byIp[row.Ip] = candidate;
            }

            candidate.Add(row);
        }

        return byIp.Values
            .Where(x => !BlacklistAndWhitelistService.IsBlacklisted(x.Ip) &&
                        !BlacklistAndWhitelistService.IsWhitelisted(x.Ip))
            .OrderByDescending(x => x.HeuristicScore)
            .ThenByDescending(x => x.LastTs)
            .ToList();
    }

    private static JevHttpThreatRequest BuildRequest(string model, ThreatCandidate candidate, int lookbackHours)
    {
        return new JevHttpThreatRequest
        {
            Model = model,
            State = candidate.ToState(lookbackHours),
            Questions = Questions.ToDictionary(x => x.Key,
                x => new JevQuestion { Type = "noul", Instructions = x.Value })
        };
    }

    private static void InsertEvaluation(SqliteConnection connection, string batchId, ThreatCandidate candidate,
        long evaluatedAt, double? malicious, double? automated, bool blocked, string? error, JevResult result)
    {
        Execute(connection,
            """
            INSERT INTO jev_threat_evaluation
                (batch_id, ip, evaluated_at, first_request_id, last_request_id, request_count,
                 malicious_probability, automated_probability, blocked, model, latency_ms, input_tokens, error)
            VALUES (@batch, @ip, @at, @first, @last, @count, @malicious, @automated, @blocked,
                    @model, @latency, @tokens, @error)
            """,
            parameters:
            [
                new P("@batch", batchId), new P("@ip", candidate.Ip), new P("@at", evaluatedAt),
                new P("@first", candidate.FirstRequestId), new P("@last", candidate.LastRequestId),
                new P("@count", candidate.Requests), new P("@malicious", malicious),
                new P("@automated", automated), new P("@blocked", blocked ? 1 : 0),
                new P("@model", result.Response?.Model ?? string.Empty), new P("@latency", result.LatencyMs),
                new P("@tokens", result.Response?.Usage?.InputTokens), new P("@error", error)
            ]);
    }

    private static void UpdateWatermark(SqliteConnection connection, ThreatCandidate candidate, long evaluatedAt,
        double risk, string batchId, bool blocked)
    {
        Execute(connection,
            """
            INSERT INTO jev_threat_state
                (ip, last_request_id, last_evaluated_at, last_risk, last_batch_id, last_blocked)
            VALUES (@ip, @last, @at, @risk, @batch, @blocked)
            ON CONFLICT(ip) DO UPDATE SET
                last_request_id = excluded.last_request_id,
                last_evaluated_at = excluded.last_evaluated_at,
                last_risk = excluded.last_risk,
                last_batch_id = excluded.last_batch_id,
                last_blocked = excluded.last_blocked
            """,
            parameters:
            [
                new P("@ip", candidate.Ip), new P("@last", candidate.LastRequestId),
                new P("@at", evaluatedAt), new P("@risk", risk), new P("@batch", batchId),
                new P("@blocked", blocked ? 1 : 0)
            ]);
    }

    private static double? Probability(Dictionary<string, JevAnswer>? answers, string key)
    {
        return answers != null && answers.TryGetValue(key, out var answer) ? answer.Noul : null;
    }

    private static JevThreatRunStatusDto MapStatus(SqliteDataReader r)
    {
        return new JevThreatRunStatusDto
        {
            BatchId = r.GetStringOrEmpty(0),
            TriggerType = r.GetStringOrEmpty(1),
            StartedAt = DateTimeOffset.FromUnixTimeSeconds(r.GetLong(2)),
            FinishedAt = r.IsDBNull(3) ? null : DateTimeOffset.FromUnixTimeSeconds(r.GetLong(3)),
            Threshold = r.GetDoubleOrZero(4),
            TotalCandidates = r.GetInt(5),
            EvaluatedIps = r.GetInt(6),
            BlockedIps = r.GetInt(7),
            FailedIps = r.GetInt(8),
            BlacklistName = r.IsDBNull(9) ? null : r.GetString(9),
            Status = r.GetStringOrEmpty(10),
            Error = r.IsDBNull(11) ? null : r.GetString(11)
        };
    }

    private sealed record ThreatRequestRow(
        long Id, long Ts, string Ip, string Host, string Path, string Method, int Status, int Blocked);

    private sealed class ThreatCandidate(string ip)
    {
        private readonly Counter _paths = new();
        private readonly Counter _hosts = new();
        private readonly Counter _methods = new();
        private readonly Dictionary<RequestTarget, int> _targets = new();
        private readonly HashSet<string> _suspiciousExamples = new(StringComparer.Ordinal);
        private readonly List<long> _timestamps = new();

        public string Ip { get; } = ip;
        public long FirstRequestId { get; private set; }
        public long LastRequestId { get; private set; }
        public long FirstTs { get; private set; }
        public long LastTs { get; private set; }
        public int Requests { get; private set; }
        public int NotFound { get; private set; }
        public int FourXx { get; private set; }
        public int Blocked { get; private set; }
        public int SuspiciousHits { get; private set; }

        public double HeuristicScore =>
            SuspiciousHits * 100d + NotFound * 3d + FourXx * 2d + _paths.Count * 5d + Requests * 0.5d;

        public void Add(ThreatRequestRow row)
        {
            if (FirstRequestId == 0) FirstRequestId = row.Id;
            LastRequestId = row.Id;
            if (FirstTs == 0) FirstTs = row.Ts;
            LastTs = row.Ts;
            Requests++;
            if (row.Status == 404) NotFound++;
            if (row.Status is >= 400 and < 500) FourXx++;
            if (row.Blocked != 0) Blocked++;
            _paths.Add(row.Path);
            _hosts.Add(row.Host);
            _methods.Add(row.Method);
            var target = new RequestTarget(row.Host, row.Method, row.Path, row.Status);
            _targets[target] = _targets.GetValueOrDefault(target) + 1;
            _timestamps.Add(row.Ts);

            var signature = AdaptiveThreatDetector.AnalyzePath(row.Path, row.Method);
            if (signature.Weight <= 0) return;
            SuspiciousHits++;
            if (_suspiciousExamples.Count < 8) _suspiciousExamples.Add(Truncate(row.Path, 180));
        }

        public HttpThreatFeatureState ToState(int lookbackHours)
        {
            return new HttpThreatFeatureState
            {
                WindowHours = lookbackHours,
                Requests = Requests,
                DistinctPaths = _paths.Count,
                DistinctHosts = _hosts.Count,
                NotFound = NotFound,
                NotFoundRatio = Requests == 0 ? 0 : Math.Round((double)NotFound / Requests, 3),
                FourXx = FourXx,
                FourXxRatio = Requests == 0 ? 0 : Math.Round((double)FourXx / Requests, 3),
                BlockedRequests = Blocked,
                SuspiciousPathHits = SuspiciousHits,
                MaxRequestsPerMinute = MaxRequestsPerMinute(_timestamps),
                Methods = _methods.Top(8),
                TopHosts = _hosts.Top(8).Select(x => Truncate(x, 180)).ToList(),
                TopPaths = _paths.Top(12).Select(x => Truncate(x, 180)).ToList(),
                RequestTargets = _targets
                    .OrderByDescending(x => x.Value)
                    .ThenBy(x => x.Key.Host)
                    .ThenBy(x => x.Key.Path)
                    .Take(30)
                    .Select(x => new HttpThreatRequestTarget
                    {
                        Host = Truncate(x.Key.Host, 180),
                        Method = Truncate(x.Key.Method, 16),
                        Path = Truncate(x.Key.Path, 220),
                        Status = x.Key.Status,
                        Count = x.Value
                    })
                    .ToList(),
                SuspiciousPathExamples = _suspiciousExamples.Take(8).ToList()
            };
        }

        private readonly record struct RequestTarget(string Host, string Method, string Path, int Status);
    }

    private sealed class Counter
    {
        private readonly Dictionary<string, int> _values = new(StringComparer.Ordinal);

        public int Count => _values.Count;

        public void Add(string value)
        {
            _values[value] = _values.GetValueOrDefault(value) + 1;
        }

        public List<string> Top(int take)
        {
            return _values.OrderByDescending(x => x.Value).ThenBy(x => x.Key).Take(take).Select(x => x.Key).ToList();
        }
    }

    private static int MaxRequestsPerMinute(List<long> timestamps)
    {
        timestamps.Sort();
        var left = 0;
        var maximum = 0;
        for (var right = 0; right < timestamps.Count; right++)
        {
            while (timestamps[right] - timestamps[left] >= 60) left++;
            maximum = Math.Max(maximum, right - left + 1);
        }

        return maximum;
    }

    private static string Truncate(string value, int max) => value.Length <= max ? value : value[..max];
